const run = (fn: string, args: unknown, subject?: string, email = 'parent@example.test') => {
  const parameters = ['node_modules/convex/bin/main.js', 'run', fn, JSON.stringify(args), ...(subject ? ['--identity', JSON.stringify({ subject, issuer: 'https://daymark-test.invalid', tokenIdentifier: `https://daymark-test.invalid|${subject}`, email, emailVerified: true })] : [])]
  const result = spawnSync(process.execPath, parameters, { encoding: 'utf8' })
  if (result.status !== 0) throw new Error(result.stderr.replace(/https:\/\/dashboard[^\s]+/g, '[local dashboard]'))
  return result.stdout.trim() ? JSON.parse(result.stdout) : undefined
}
