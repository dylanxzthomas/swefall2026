import { expect, test } from '@playwright/test'
for (const scheme of ['light', 'dark'] as const) test(`email responsibility is reviewable on Tasks and saves unfinished in ${scheme}`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: scheme })
  await page.goto('/e2e.html?scenario=email-followup-tasks')
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Tasks suggested from email' })).toBeVisible()
  await page.getByRole('button', { name: 'For you', exact: true }).click()
  await expect(page.getByText('Nothing needs you right now.', { exact: true })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Task title', exact: true }).fill('Sign Maya’s form')
  await page.getByRole('button', { name: 'Add to my tasks', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Tasks suggested from email' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit Sign Maya’s form' })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Mark Sign Maya’s form complete' })).not.toBeChecked()
  const state = await page.evaluate(() => JSON.parse(sessionStorage.getItem('synthetic-state') ?? '{}'))
  expect(state.personalTasks).toHaveLength(1); expect(state.personalTasks[0].done).toBe(false)
  await page.reload(); await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit Sign Maya’s form' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
