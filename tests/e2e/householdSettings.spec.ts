import { expect, test } from '@playwright/test'

for (const variant of [
  { name: 'small light', width: 375, height: 667, color: 'light' as const, large: false },
  { name: 'dark', width: 390, height: 844, color: 'dark' as const, large: false },
  { name: 'large text', width: 375, height: 812, color: 'light' as const, large: true },
]) {
  test(`household rows keep forms deliberate and settings reachable at ${variant.name}`, async ({ page }) => {
    await page.setViewportSize({ width: variant.width, height: variant.height })
    await page.emulateMedia({ colorScheme: variant.color, reducedMotion: 'reduce' })
    await page.goto('/')
    if (variant.large) await page.addStyleTag({ content: 'html:root { font-size: 212.5%; }' })
    if (variant.large) expect(await page.evaluate(() => getComputedStyle(document.documentElement).fontSize)).toBe('34px')
    const composer = page.getByLabel('What can I handle?', { exact: true })
    await composer.fill('A note I have not sent')
    await page.getByRole('button', { name: 'Household settings', exact: true }).click()
    const settings = page.getByRole('dialog', { name: 'Household', exact: true })
    await expect(settings.getByLabel('Add a child', { exact: true })).toBeHidden()
    await expect(settings.getByRole('heading', { name: 'You and your family' })).toBeVisible()
    await expect(settings.getByRole('heading', { name: 'Connections', exact: true })).toBeVisible()
    await expect(settings.getByRole('region', { name: 'Gmail connection', exact: true })).toBeVisible()
    if (variant.large) expect(await settings.getByRole('heading', { name: 'Gmail', exact: true }).evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(30)
    const family = settings.locator('summary').filter({ hasText: 'Children and timezone' })
    await family.focus(); await page.keyboard.press('Enter')
    await expect(settings.getByLabel('Add a child', { exact: true })).toBeVisible()
    await expect(settings.getByLabel('Household timezone', { exact: true })).toBeVisible()
    await settings.getByLabel('Add a child', { exact: true }).fill('Unstored child')
    await family.focus(); await page.keyboard.press('Enter')
    await expect(settings.getByLabel('Add a child', { exact: true })).toBeHidden()
    await family.focus(); await page.keyboard.press('Enter')
    await expect(settings.getByLabel('Add a child', { exact: true })).toHaveValue('Unstored child')
    await family.click()
    await settings.getByText('Data and privacy', { exact: true }).click()
    await expect(settings.getByRole('heading', { name: 'On this device', exact: true })).toBeVisible()
    await expect(settings.getByText('No account is needed; notices are not uploaded to a model.', { exact: false })).toBeVisible()
    await settings.getByText('Delete saved device data', { exact: true }).first().click()
    await expect(settings.getByRole('button', { name: 'Delete saved device data', exact: true })).toBeDisabled()
    await settings.getByRole('button', { name: 'Delete saved device data', exact: true }).scrollIntoViewIfNeeded()
    expect(await settings.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expect(settings.getByRole('button', { name: 'Close', exact: true })).toBeInViewport()
    await settings.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(composer).toHaveValue('A note I have not sent')
    await page.getByRole('button', { name: 'Household settings', exact: true }).click()
    await expect(settings.getByLabel('Add a child', { exact: true })).toBeHidden()
    expect(await settings.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    const heading = await settings.getByRole('heading', { name: 'Household', exact: true }).boundingBox()
    const done = await settings.getByRole('button', { name: 'Close', exact: true }).boundingBox()
    expect(heading && done && heading.x + heading.width <= done.x).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`household-${variant.name.replaceAll(' ', '-')}.png`) })
    await page.keyboard.press('Escape')
    await expect(settings).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Household settings', exact: true })).toBeFocused()
  })
}
