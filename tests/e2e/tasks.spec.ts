test('scheduled assistant work uses household time, persists, cancels honestly, and prepares overdue local work without approving it', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.clock.setFixedTime(new Date('2026-10-01T18:00:00Z'))
  await page.goto('/')
  await page.getByRole('button', { name: 'Household settings' }).click()
  await page.getByText('Children and timezone', { exact: true }).click()
  await page.getByLabel('Household timezone', { exact: true }).fill('America/Los_Angeles')
  await page.getByRole('button', { name: 'Save household', exact: true }).click()
  await openTasks(page)
  const schedule = async (text: string) => {
    await taskRegion(page).locator('.dm-task-new').click()
    const add = page.getByRole('dialog', { name: 'Add a task', exact: true })
    await add.getByRole('group', { name: 'Task owner' }).getByRole('button', { name: 'Sola', exact: true }).click()
    await add.getByRole('textbox', { name: 'What should Sola prepare?', exact: true }).fill(text)
    await add.getByRole('checkbox', { name: 'Prepare later', exact: true }).check()
    await add.getByLabel('Preparation time', { exact: false }).fill('2026-10-02T09:00')
    await expect(add).toContainText('preparation runs when Daymark is open')
    await expect(add).toContainText('still needs your approval')
    await add.getByRole('button', { name: 'Schedule preparation', exact: true }).click()
    await expect(add).toHaveCount(0)
  }
  const request = 'Draft email to teacher@example.test\nSubject: Tomorrow RSVP\nBody: Please save Maya a place.'
  await schedule(request)
  let saved = await savedWorkspace(page)
  expect(saved.state.jobs[0]).toMatchObject({ scheduledFor: new Date('2026-10-02T16:00:00Z').getTime(), preparing: false, actions: [] })
  await page.reload()
  await openTasks(page)
  await expect(taskRegion(page)).toContainText('Sola · Scheduled')
  await expect(taskRegion(page)).toContainText('America/Los_Angeles')
  await taskRegion(page).locator('.dm-task-row').click()
  await expect(page.getByRole('region', { name: 'Conversation', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /^Review scheduled request:/ }).click()
  const scheduled = page.getByRole('dialog', { name: 'Review request', exact: true })
  await scheduled.getByText('Source & more options', { exact: true }).click()
  await scheduled.getByRole('button', { name: 'Cancel pending work', exact: true }).click()
  await scheduled.getByRole('button', { name: 'Close', exact: true }).click()
  await openTasks(page)
  await taskRegion(page).getByRole('group', { name: 'Filter tasks' }).getByRole('button', { name: 'Finished', exact: true }).click()
  await expect(taskRegion(page)).toContainText('Cancelled')
  saved = await savedWorkspace(page)
  expect(saved.state.jobs[0].cancelled).toBe(true)
  expect(saved.state.jobs[0].actions).toEqual([])
  await schedule(request.replace('Tomorrow RSVP', 'New RSVP'))
  await taskRegion(page).getByRole('group', { name: 'Filter tasks' }).getByRole('button', { name: 'All', exact: true }).click()
  await taskRegion(page).locator('.dm-task-row').filter({ hasText: 'Scheduled' }).click()
  await page.clock.setFixedTime(new Date('2026-10-02T16:01:00Z'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await page.getByRole('button', { name: /^Review request:/ }).click()
  await expect(page.getByRole('dialog', { name: 'Review request' })).toContainText('Please save Maya a place.')
  await page.reload()
  await openTasks(page)
  await expect(taskRegion(page)).toContainText('Email draft · not sent')
  saved = await savedWorkspace(page)
  const prepared = saved.state.jobs.find((job: any) => !job.cancelled)
  expect(prepared.actions).toHaveLength(1)
  expect(prepared.actions[0]).toMatchObject({ status: 'review', receipts: [] })
  expect(saved.state.plan).toEqual([])
  expect(saved.state.arrangements).toEqual([])
  expect(pageErrors).toEqual([])
})

