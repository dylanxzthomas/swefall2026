async function savedWorkspace(page: Page) {
  return page.evaluate(() => new Promise<any>((resolve, reject) => {
    const request = indexedDB.open('daymark-device-v1')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result, tx = db.transaction('workspace'), read = tx.objectStore('workspace').get('current')
      read.onsuccess = () => resolve(read.result)
      tx.oncomplete = () => db.close()
    }
  }))
}
const taskRegion = (page: Page) => page.getByRole('region', { name: 'Tasks', exact: true })
const taskSheet = (page: Page) => page.getByRole('dialog', { name: 'Your task', exact: true })
async function openTasks(page: Page) {
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Tasks', exact: true }).click()
}
async function addPersonalTask(page: Page, title: string) {
  await taskRegion(page).locator('.dm-task-new').click()
  const add = page.getByRole('dialog', { name: 'Add a task', exact: true })
  await add.getByLabel('Task', { exact: true }).fill(title)
  return add
}

