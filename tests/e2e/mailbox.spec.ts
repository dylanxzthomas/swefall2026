import { expect, test, type Page } from '@playwright/test'

const actions = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('mailbox-actions') ?? '[]'))
async function open(page: Page, scenario = 'mailbox-connected') { await page.setViewportSize({ width: 390, height: 844 }); await page.goto(`/e2e.html?scenario=${scenario}`) }
async function send(page: Page, text = 'Check my inbox') { await page.getByRole('textbox', { name: 'What can I handle?' }).fill(text); await page.getByRole('button', { name: 'Send', exact: true }).click() }
async function source(page: Page) {
  await page.getByLabel('Email details', { exact: true }).last().click()
  await page.getByRole('button', { name: /Field trip on October 12 school@example.test/ }).last().click()
  return page.getByRole('dialog', { name: 'Private email', exact: true })
}
async function draft(page: Page) {
  await page.getByText('Prepare a reply', { exact: true }).click()
  await page.getByRole('textbox', { name: 'Reply instructions' }).fill('Confirm Maya will attend.')
  await page.getByRole('button', { name: 'Prepare reply', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review your reply', exact: true })).toBeVisible()
}
