for (const kind of ['draft', 'send'] as const) {
  test(`Tasks keeps an uncertain ${kind} reachable after its source disappears and checks without another write`, async ({ page }) => {
    await open(page, `mailbox-recovery-${kind}`)
    await page.getByLabel('What can I handle?').fill('Keep my unsent reply')
    await page.getByRole('button', { name: 'Tasks', exact: true }).click()
    await page.getByRole('group', { name: 'Filter tasks' }).getByRole('button', { name: 'For you', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Nothing needs you' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Open email reply: Re: Lost source recovery', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const reply = page.getByRole('article', { name: 'Email reply: Re: Lost source recovery', exact: true })
    await expect(reply).toBeFocused()
    await expect(page.getByLabel('What can I handle?')).toHaveValue('Keep my unsent reply')
    await reply.getByRole('button', { name: 'Review email reply', exact: true }).click()
    const review = page.getByRole('dialog', { name: 'Private email reply', exact: true })
    await expect(review.getByText('Only you can see this', { exact: true })).toBeVisible()
    await expect(review.getByText(/source email changed or is no longer available/)).toBeVisible()
    await expect(review.getByRole('button', { name: 'Approve & send email', exact: true })).toHaveCount(0)
    await review.getByRole('button', { name: kind === 'draft' ? 'Check draft status' : 'Check send result', exact: true }).click()
    await expect(review.getByRole('heading', { name: kind === 'draft' ? 'Saved in Gmail Drafts' : 'Sent copy verified', exact: true })).toBeVisible()
    if (kind === 'draft') await expect(review.getByRole('button', { name: 'Approve & send email', exact: true })).toBeDisabled()
    expect((await actions(page)).map((a: {action: string}) => a.action)).toEqual([kind === 'draft' ? 'reconcile-draft' : 'reconcile-send'])
    await review.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Tasks', exact: true }).click()
    if (kind === 'send') {
      await page.getByRole('group', { name: 'Filter tasks' }).getByRole('button', { name: 'Finished', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Open email reply: Re: Lost source recovery', exact: true })).toBeVisible()
    }
    await page.getByRole('searchbox', { name: 'Search tasks', exact: true }).fill('does not match')
    await expect(page.getByRole('button', { name: /Open email reply:/ })).toHaveCount(0)
    await page.getByRole('searchbox', { name: 'Search tasks', exact: true }).fill('Lost source')
    await expect(page.getByRole('button', { name: 'Open email reply: Re: Lost source recovery', exact: true })).toBeVisible()
  })
}
