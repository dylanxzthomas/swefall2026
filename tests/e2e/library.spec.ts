import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a3ioAAAAASUVORK5CYII=', 'base64')
const details = (page: Page) => page.getByRole('dialog', { name: 'Saved file', exact: true })
async function library(page: Page) {
  await page.getByRole('button', { name: 'Library', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Library', exact: true })).toBeVisible()
}
async function workspace(page: Page) {
  return page.evaluate(() => new Promise<any>((resolve, reject) => {
    const request = indexedDB.open('daymark-device-v1')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result, tx = db.transaction('workspace'), read = tx.objectStore('workspace').get('current')
      read.onsuccess = () => resolve(read.result)
      tx.oncomplete = () => db.close()
    }
  }))
}
async function upload(page: Page, name = 'synthetic-notice.png') {
  await page.getByLabel('Choose Library files').setInputFiles({ name, mimeType: 'image/png', buffer: png })
  const add = page.getByRole('dialog', { name: 'Add to Library', exact: true })
  await expect(add).toBeVisible()
  return add
}

test('Library saves files only on request, previews real bytes, edits and persists metadata, and downloads the original', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Household settings' }).click()
  await page.getByText('Children and timezone', { exact: true }).click()
  await page.getByLabel('Add a child', { exact: true }).fill('Maya')
  await page.getByRole('button', { name: 'Save household', exact: true }).click()
  await library(page)
  await expect(page.getByText('A place for useful work.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Media', exact: true }).click()
  await expect(page.getByText('School files, together.', { exact: true })).toBeVisible()
  const add = await upload(page)
  expect((await workspace(page)).state.library).toEqual([])
  await add.getByLabel('Collection', { exact: true }).fill('School')
  await add.getByRole('combobox', { name: 'Child', exact: true }).selectOption({ label: 'Maya' })
  await add.getByRole('button', { name: 'Add file', exact: true }).click()
  await expect(add).toHaveCount(0)
  await page.getByRole('button', { name: 'Open synthetic-notice.png', exact: true }).click()
  const image = details(page).getByRole('img', { name: 'synthetic-notice.png', exact: true })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(1)
  await details(page).getByText('Edit details', { exact: true }).click()
  await details(page).getByLabel('Title', { exact: true }).fill('Museum permission slip')
  await details(page).getByLabel('Collection', { exact: true }).fill('Trips')
  await details(page).getByRole('checkbox', { name: 'Pin to top' }).check()
  await details(page).getByRole('button', { name: 'Save details', exact: true }).click()
  await expect(details(page).getByText('Details saved.', { exact: true })).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await details(page).getByRole('link', { name: 'Download image' }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('Museum permission slip.png')
  expect(await readFile((await download.path())!)).toEqual(png)
  await details(page).getByRole('button', { name: 'Close library details' }).click()
  await page.reload()
  await library(page)
  await page.getByRole('button', { name: 'Media', exact: true }).click()
  await page.getByRole('combobox', { name: 'Library collection' }).selectOption('Trips')
  await page.getByRole('searchbox', { name: 'Search Library' }).fill('Maya')
  await expect(page.getByRole('button', { name: 'Open Museum permission slip', exact: true })).toBeVisible()
  const saved = (await workspace(page)).state.library[0]
  expect(saved).toMatchObject({ title: 'Museum permission slip', collection: 'Trips', pinned: true, version: 2 })
  expect(saved.childId).toBeTruthy()
  await page.screenshot({ path: 'test-results/daymark-library-media-dark.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Edit Museum permission slip', exact: true }).click()
  await details(page).getByRole('button', { name: 'Remove from Library', exact: true }).click()
  expect((await workspace(page)).state.library).toHaveLength(1)
  await details(page).getByRole('button', { name: 'Remove from Library', exact: true }).click()
  await expect(details(page)).toHaveCount(0)
  expect((await workspace(page)).state.library).toEqual([])
})

test('Library rejects stale editing and removal after a successful save in the same open sheet', async ({ page, context }) => {
  await page.goto('/')
  await library(page)
  const add = await upload(page)
  await add.getByRole('button', { name: 'Add file', exact: true }).click()
  await page.getByRole('button', { name: 'Edit synthetic-notice.png', exact: true }).click()
  await details(page).getByText('Edit details', { exact: true }).click()
  await details(page).getByLabel('Title', { exact: true }).fill('My renamed notice')
  await details(page).getByRole('button', { name: 'Save details', exact: true }).click()
  await expect(details(page).getByText('Details saved.', { exact: true })).toBeVisible()
  await details(page).getByRole('button', { name: 'Remove from Library', exact: true }).click()
  const other = await context.newPage()
  await other.goto('/')
  await library(other)
  await other.getByRole('button', { name: 'Media', exact: true }).click()
  await other.getByRole('button', { name: 'Edit My renamed notice', exact: true }).click()
  await details(other).getByText('Edit details', { exact: true }).click()
  await details(other).getByLabel('Title', { exact: true }).fill('Latest shared title')
  await details(other).getByRole('button', { name: 'Save details', exact: true }).click()
  await expect(details(other).getByText('Details saved.', { exact: true })).toBeVisible()
  await expect(details(page).getByRole('alert')).toContainText('This item changed elsewhere')
  await expect(details(page).getByRole('button', { name: 'Remove from Library', exact: true })).toBeDisabled()
  await expect(details(page).getByRole('button', { name: 'Save details', exact: true })).toBeDisabled()
  expect((await workspace(page)).state.library[0]).toMatchObject({ title: 'Latest shared title', version: 3 })
})

test('saved work keeps a canonical draft reference and never reports an unsent email as completed', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('What can I handle?').fill('Draft email to teacher@example.test\nSubject: Museum RSVP\nBody: Maya will attend. Thank you.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByRole('button', { name: /^Review request:/ }).last().click()
  const review = page.getByRole('dialog', { name: 'Review request' })
  await expect(review).toBeVisible()
  await review.getByText('Keep in Library', { exact: true }).click()
  await review.getByRole('button', { name: /Save .* to Library/ }).click()
  await expect(review.getByText('Saved to Library. No action was approved or sent.', { exact: true })).toBeVisible()
  await review.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(review).toHaveCount(0)
  await library(page)
  await expect(page.getByText('Draft · not sent', { exact: true })).toBeVisible()
  await expect(page.locator('.dm-library-artifact')).toContainText('Maya will attend')
  await page.locator('.dm-library-artifact-main').click()
  await page.locator('.dm-conversation-work:focus').getByRole('button', { name: /^Review request:/ }).click()
  await review.getByText('Edit details', { exact: true }).click()
  await review.getByRole('textbox', { name: 'Message', exact: true }).fill('Please reserve two seats. Thank you.')
  await review.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(review).toHaveCount(0)
  await library(page)
  await expect(page.locator('.dm-library-artifact')).toContainText('Please reserve two seats')
  const saved = await workspace(page)
  expect(saved.state.library).toHaveLength(1)
  expect(saved.state.jobs[0].actions[0].status).toBe('review')
  expect(saved.state.jobs[0].actions[0].receipts).toEqual([])
  expect(saved.state.plan).toEqual([])
})

