import { expect, test, type Page } from '@playwright/test'
async function open(page: Page, scenario = 'email-watch-followups') {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/e2e.html?scenario=${scenario}`)
  await page.getByText('Email watch', { exact: true }).click()
  await page.getByText('Recent email checks', { exact: true }).click()
}
const actions = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('watch-actions') ?? '[]'))
const tasks = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('saved-email-tasks') ?? '[]'))
for (const scheme of ['light', 'dark'] as const) test(`edited email task saves once as unfinished with readable source context in ${scheme}`, async ({ page }) => {
  await page.emulateMedia({ colorScheme: scheme }); await open(page)
  await page.getByText('Related emails (2)', { exact: true }).click()
  await expect(page.getByText('Re: Field trip details — return time', { exact: true })).toBeVisible()
  await expect(page.locator('.dm-email-related time').first()).toHaveAttribute('datetime', '2026-10-04T15:00:00.000Z')
  await page.getByText('Why this task?', { exact: true }).click()
  await expect(page.locator('.dm-email-task blockquote')).toHaveText('Please return the signed form by October 10.')
  await expect(page.getByText('Check the due date before saving.', { exact: true })).toBeVisible()
  await page.getByLabel('Task title', { exact: true }).fill('Sign Maya’s trip form')
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Put the signed form in her backpack.')
  await page.getByLabel('Due date', { exact: true }).fill('2026-10-09')
  await page.getByRole('combobox', { name: 'Child', exact: true }).selectOption('maya')
  const card = page.getByRole('region', { name: 'Suggested task: Return field-trip form' })
  await card.scrollIntoViewIfNeeded()
  const sheet = page.getByRole('dialog', { name: 'Household' })
  expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath(`email-followup-${scheme}.png`), animations: 'disabled' })
  // Two activation events before React commits must still enter the save handler only once.
  await page.getByRole('button', { name: 'Add to my tasks', exact: true }).evaluate(button => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click() })
  await expect(page.getByLabel('Task title', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Due date', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Dismiss suggestion', exact: true })).toBeDisabled()
  await expect(page.getByText('Added to your tasks · saving did not complete the work', { exact: true })).toBeVisible()
  await expect(page.getByText('Sign Maya’s trip form', { exact: true })).toBeVisible()
  expect(await actions(page)).toEqual(['save-task'])
  expect(await tasks(page)).toEqual([{ title: 'Sign Maya’s trip form', notes: 'Put the signed form in her backpack.', dueDate: '2026-10-09', childId: 'maya', done: false }])
})
test('stale task or message actions preserve edits and never announce success', async ({ page }) => {
  await open(page, 'email-watch-followups-stale')
  await page.getByLabel('Task title', { exact: true }).fill('My reviewed title')
  await page.getByRole('button', { name: 'Add to my tasks', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('original email changed')
  await expect(page.getByLabel('Task title', { exact: true })).toHaveValue('My reviewed title')
  await expect(page.getByText('Added to your tasks · saving did not complete the work', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Snooze for a day', exact: true }).click()
  await expect(page.getByRole('alert').last()).toContainText('email changed')
  expect(await tasks(page)).toEqual([]); expect(await actions(page)).toEqual([])
})
test('an arriving newer suggestion does not silently replace edits or permit an outdated save', async ({ page }) => {
  await open(page, 'email-watch-followups-changed')
  await page.getByLabel('Task title', { exact: true }).fill('My current edit')
  await page.getByRole('button', { name: 'Simulate newer suggestion', exact: true }).click()
  await expect(page.getByLabel('Task title', { exact: true })).toHaveValue('My current edit')
  await expect(page.getByRole('button', { name: 'Add to my tasks', exact: true })).toBeDisabled()
  await expect(page.getByText(/This suggestion changed while you were editing/)).toBeVisible()
  await page.getByRole('button', { name: 'Load latest suggestion', exact: true }).click()
  await expect(page.getByLabel('Task title', { exact: true })).toHaveValue('Review corrected field-trip form')
  await expect(page.getByRole('button', { name: 'Add to my tasks', exact: true })).toBeEnabled()
  expect(await tasks(page)).toEqual([]); expect(await actions(page)).toEqual([])
})
test('snooze, restore, dismissal and retry stay separate from completing work', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: 'Snooze for a day', exact: true }).click()
  await expect(page.getByText(/^Snoozed until /)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add to my tasks', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Restore message', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add to my tasks', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Dismiss message', exact: true }).click()
  await expect(page.getByText('Set aside · no work marked done', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Restore message', exact: true }).click()
  await page.getByRole('button', { name: 'Dismiss suggestion', exact: true }).click()
  await expect(page.getByText('Suggestion dismissed · no task added', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Try preparation again', exact: true }).click()
  await expect(page.getByText('Preparing for review', { exact: true })).toBeVisible()
  await expect(page.getByText('Preparation requested again. Nothing has been sent.', { exact: true })).toBeVisible()
  expect(await tasks(page)).toEqual([])
  expect(await actions(page)).toEqual(['snooze', 'restore', 'dismiss', 'restore', 'dismiss-task', 'retry-message'])
})
test('changed access disables saving and omits unavailable handling controls', async ({ page }) => {
  await open(page, 'email-watch-followups-unavailable')
  await expect(page.getByRole('button', { name: 'Add to my tasks', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Dismiss suggestion', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Snooze for a day', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Dismiss message', exact: true })).toHaveCount(0)
  await expect(page.getByText(/This suggestion cannot be saved right now/)).toBeVisible()
  expect(await actions(page)).toEqual([])
})
