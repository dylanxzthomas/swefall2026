import { expect, test } from '@playwright/test'
for (const scheme of ['light', 'dark'] as const) test(`filtered email remains inspectable and can be restored in ${scheme}`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: scheme })
  await page.goto('/e2e.html?scenario=email-watch-triage')
  await page.getByText('Email watch', { exact: true }).click()
  await page.getByText('Recent email checks', { exact: true }).click()
  await expect(page.getByText('Kept quiet · no task created', { exact: true })).toBeVisible()
  await expect(page.getByText('This is not an all-clear for your inbox.', { exact: false })).toBeVisible()
  await page.getByText('Email excerpts', { exact: true }).click()
  await expect(page.getByText('There is nothing to sign or return.', { exact: true })).toBeVisible()
  const sheet = page.getByRole('dialog', { name: 'Household' })
  expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath(`email-triage-${scheme}.png`), animations: 'disabled' })
  await page.getByRole('button', { name: 'Prepare for review', exact: true }).click()
  await expect(page.getByText('Preparing for review', { exact: true })).toBeVisible()
  await expect(page.getByText(/Preparation requested.*nothing has been sent/)).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('watch-actions') ?? '[]'))).toEqual(['review-message'])
})
test('stale or paused email checks cannot announce restoration', async ({ page }) => {
  await page.goto('/e2e.html?scenario=email-watch-triage-stale')
  await page.getByText('Email watch', { exact: true }).click(); await page.getByText('Recent email checks', { exact: true }).click()
  await page.getByRole('button', { name: 'Prepare for review', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('changed or expired')
  await expect(page.getByText('Kept quiet · no task created', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('watch-actions'))).toBeNull()
  await page.goto('/e2e.html?scenario=email-watch-triage-paused')
  await page.getByText('Email watch', { exact: true }).click(); await page.getByText('Recent email checks', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Prepare for review', exact: true })).toBeDisabled()
  await expect(page.getByText(/You can paste the original email into Assistant/)).toBeVisible()
})
