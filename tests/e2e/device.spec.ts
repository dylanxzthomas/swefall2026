test('competing plan changes require refreshing the changed original before saving', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Household settings' }).click()
  await household(page)
  await submit(page, notice)
  await page.getByRole('button', { name: 'Save to device plan', exact: true }).click()
  await expect(review(page).getByText('Saved to your device plan')).toBeVisible()
  await closeReview(page)
  const original = (await workspace(page)).state.plan[0]
  for (const location of ['East gate', 'West gate']) {
    await submit(page, notice.replace('North gate', location))
    await page.getByText('Edit details', { exact: true }).click()
    await page.getByRole('combobox', { name: 'Calendar operation', exact: true }).selectOption(original._id)
    await closeReview(page)
  }
  await page.locator('article.dm-conversation-work').filter({ hasText: 'Location: East gate' }).getByRole('button', { name: /^Review request:/ }).click()
  await page.getByRole('button', { name: 'Save to device plan', exact: true }).click()
  await expect(review(page).getByText('Saved to your device plan')).toBeVisible()
  await closeReview(page)
  await page.locator('article.dm-conversation-work').filter({ hasText: 'Location: West gate' }).getByRole('button', { name: /^Review request:/ }).click()
  await page.getByRole('button', { name: 'Save to device plan', exact: true }).click()
  await expect(review(page).getByRole('alert')).toContainText('The original plan item changed')
  expect((await workspace(page)).state.plan[0].payload.location).toBe('East gate')
  await page.getByRole('button', { name: 'Refresh current plan details' }).click()
  await page.getByRole('button', { name: 'Load latest review' }).click()
  await expect(review(page).getByText(/Previously:/)).toContainText('East gate')
  await page.getByRole('button', { name: 'Save to device plan', exact: true }).click()
  await expect(review(page).getByText('Saved to your device plan')).toBeVisible()
  const saved = await workspace(page)
  expect(saved.state.plan).toHaveLength(1)
  expect(saved.state.plan[0].payload.location).toBe('West gate')
})

test('a failed clipboard action keeps every selected draft pending and saves no partial plan', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Household settings' }).click()
  await household(page)
  await submit(page, `${notice}\nAlso draft an email to teacher@example.test.`)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Clipboard permission denied. Nothing was copied.') } } }))
  await page.getByRole('button', { name: 'Save plan & copy messages' }).click()
  await expect(review(page).getByRole('alert')).toContainText('Clipboard permission denied')
  const saved = await workspace(page)
  expect(saved.state.jobs[0].actions.every((a: any) => a.status === 'review' && a.receipts.length === 0)).toBe(true)
  expect(saved.state.plan).toEqual([])
  await page.reload()
  await expect(page.getByRole('button', { name: /Maya’s museum trip/ })).toBeVisible()
})
