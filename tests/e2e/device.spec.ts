import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const notice = 'Event: Maya’s museum trip\nDate: 2026-10-08\nTime: 8:30 AM to 2:30 PM\nLocation: North gate'
const review = (page: Page) => page.getByRole('dialog', { name: 'Review request' })
async function closeReview(page: Page) {
  await review(page).getByRole('button', { name: 'Close', exact: true }).click()
  // Done saves asynchronously; the composer stays inert until the sheet closes.
  await expect(review(page)).toHaveCount(0)
}
async function household(page: Page) {
  await page.getByText('Children and timezone', { exact: true }).click()
  await page.getByLabel('Household timezone', { exact: true }).fill('UTC')
  await page.getByLabel('Add a child', { exact: true }).fill('Maya')
  await page.getByRole('button', { name: 'Save household', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Household', exact: true })).toHaveCount(0)
}
async function submit(page: Page, text: string) {
  await page.getByLabel('What can I handle?').fill(text)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(review(page)).toHaveCount(0)
  const request = page.locator('article.dm-conversation-work').filter({ has: page.locator('.dm-request-context').getByText(text, { exact: true }) })
  await request.getByRole('button', { name: /^(?:Review|View) request:/ }).click()
  await expect(review(page)).toBeVisible()
}
async function workspace(page: Page) {
  return page.evaluate(() => new Promise<any>((resolve, reject) => {
    const open = indexedDB.open('daymark-device-v1')
    open.onerror = () => reject(open.error)
    open.onsuccess = () => {
      const db = open.result, tx = db.transaction('workspace'), request = tx.objectStore('workspace').get('current')
      request.onsuccess = () => resolve(request.result)
      tx.oncomplete = () => db.close()
    }
  }))
}

test('normal homepage saves a reviewed plan without an account, survives reload, and exports a real calendar file', async ({ page, context, baseURL }) => {
  const providerRequests: string[] = []
  context.on('request', r => { if (r.method() !== 'GET' || new URL(r.url()).origin !== new URL(baseURL!).origin) providerRequests.push(r.url()) })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(page.getByText('On this device · no sign-in needed')).toBeVisible()
  await submit(page, notice)
  // Household-wide events no longer require adding a child before review.
  await expect(page.getByRole('button', { name: 'Save to device plan', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Add a child for this draft', exact: true }).click()
  await household(page)
  await review(page).getByText('Edit details', { exact: true }).click()
  await page.getByRole('combobox', { name: 'Child', exact: true }).selectOption({ label: 'Maya' })
  await page.getByLabel('Timezone', { exact: true }).fill('UTC')
  await page.getByLabel('Location', { exact: true }).fill('South gate')
  await page.getByRole('button', { name: 'Save to device plan', exact: true }).click()
  await expect(review(page).getByText('Saved to your device plan', { exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download calendar file', exact: true }).click()
  const file = await downloadPromise
  const ics = await readFile((await file.path())!, 'utf8')
  expect(ics).toContain('DTSTART:20261008T083000Z')
  expect(ics).toContain('DTEND:20261008T143000Z')
  expect(ics).toContain('LOCATION:South gate')
  expect(ics).toContain('BEGIN:VCALENDAR')
  await closeReview(page)
  await page.reload()
  await page.getByRole('button', { name: 'Plan', exact: true }).click()
  await expect(page.getByRole('button', { name: /Maya’s museum trip/ })).toContainText('South gate')
  await page.screenshot({ path: 'test-results/daymark-device-plan.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Assistant', exact: true }).click()
  await submit(page, notice)
  await expect(review(page).getByText('Saved to your device plan', { exact: true })).toBeVisible()
  const saved = await workspace(page)
  expect(saved.state.jobs).toHaveLength(1)
  expect(saved.state.plan).toHaveLength(1)
  expect(saved.state.jobs[0].actions[0].receipts).toHaveLength(1)
  expect(providerRequests).toEqual([])
})

test('no-account email and pickup drafts copy text without claiming delivery or acceptance', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await submit(page, 'Draft email to teacher@example.test\nSubject: Maya RSVP\nBody: Maya will attend. Thank you.')
  await page.getByRole('button', { name: 'Copy email draft', exact: true }).click()
  await expect(review(page).getByText(/Email text copied. Nothing has been sent/)).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('To: teacher@example.test\nSubject: Maya RSVP\n\nMaya will attend. Thank you.')
  await closeReview(page)
  await submit(page, 'Can Alex pick up Maya on 2026-10-08 at 2 PM?')
  await expect(review(page).getByText('Copy the request and send it yourself')).toBeVisible()
  await page.getByRole('button', { name: 'Copy pickup request', exact: true }).click()
  await expect(review(page).getByText('Request text copied. No caregiver has been contacted or confirmed.')).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('Can Alex pick up Maya on 2026-10-08 at 2 PM?')
  const saved = await workspace(page)
  expect(saved.state.jobs.every((j: any) => j.actions.every((a: any) => a.status === 'review' && a.receipts.length === 0))).toBe(true)
  expect(saved.state.arrangements).toEqual([])
  expect(saved.state.plan).toEqual([])
  await page.reload()
  await expect(page.getByRole('button', { name: /Pickup request/ })).toBeVisible()
})

test('device edits reject stale reviews from a second tab and stay isolated from another browser profile', async ({ page, context, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Household settings' }).click()
  await household(page)
  await submit(page, notice)
  const other = await context.newPage()
  await other.goto('/')
  await other.getByRole('button', { name: /Maya’s museum trip/ }).click()
  await other.getByText('Edit details', { exact: true }).click()
  await other.getByLabel('Location', { exact: true }).fill('West gate')
  await closeReview(other)
  await expect(page.getByRole('button', { name: 'Load latest review', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save to device plan', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Load latest review', exact: true }).click()
  await expect(review(page).locator('.dm-preview')).toContainText('West gate')
  await page.getByRole('button', { name: 'Save to device plan', exact: true }).click()
  await expect(review(page).getByText('Saved to your device plan', { exact: true })).toBeVisible()
  await other.getByRole('button', { name: 'Plan', exact: true }).click()
  await expect(other.getByRole('button', { name: /Maya’s museum trip/ })).toContainText('West gate')
  const isolated = await browser.newContext()
  try {
    const isolatedPage = await isolated.newPage()
    await isolatedPage.goto(new URL('/', page.url()).href)
    await expect(isolatedPage.getByText('On this device · no sign-in needed')).toBeVisible()
    expect((await workspace(isolatedPage)).state.jobs).toEqual([])
    expect((await workspace(isolatedPage)).state.household.children).toEqual([])
  } finally { await isolated.close() }
})

