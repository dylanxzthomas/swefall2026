import { test, expect } from '@playwright/test'
test.use({ viewport: { width: 390, height: 844 } })
const start = async (page: import('@playwright/test').Page) => { await page.goto('/e2e.html?scenario=mailbox-followthrough'); await expect(page.getByText('Synthetic private Gmail preview', { exact: false })).toBeVisible() }
const actions = (page: import('@playwright/test').Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('mailbox-actions') ?? '[]') as { action: string; data?: any }[])
test('Tasks focuses the existing follow-up in the main conversation without opening review or losing the composer', async ({ page }) => {
  await start(page)
  await page.getByRole('textbox', { name: 'What can I handle?' }).fill('My unsent household question')
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await page.getByRole('region', { name: 'Tasks', exact: true }).getByRole('button', { name: /Return Maya’s form/ }).click()
  await expect(page.getByRole('button', { name: 'Assistant', exact: true })).toHaveAttribute('aria-current', 'page')
  const target = page.getByRole('group', { name: 'Email follow-up: Return Maya’s form', exact: true })
  await expect(target).toBeFocused()
  await expect(target).toHaveCount(1)
  await expect(page.getByRole('article', { name: 'Private email conversation' })).toHaveCount(1)
  await expect(page.getByRole('article', { name: 'Retained email follow-up' })).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'What can I handle?' })).toHaveValue('My unsent household question')
  expect(await actions(page)).toEqual([])
  await target.getByRole('button', { name: 'Review follow-up: Return Maya’s form' }).click()
  await expect(page.getByRole('dialog', { name: 'Private follow-up' })).toBeVisible()
  expect(await actions(page)).toEqual([])
})
test('retained follow-ups stay reachable without a visible run and disappear as fallback copies when it returns', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Hide synthetic email run' }).click()
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await page.getByRole('region', { name: 'Tasks', exact: true }).getByRole('button', { name: /Confirm attendance/ }).click()
  const target = page.getByRole('group', { name: 'Email follow-up: Confirm attendance', exact: true })
  await expect(target).toBeFocused()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(target).toHaveCount(1)
  await target.getByRole('button', { name: 'Review follow-up: Confirm attendance' }).click()
  await expect(page.getByRole('dialog', { name: 'Private follow-up' }).getByRole('button', { name: 'Review email draft' })).toBeEnabled()
  await page.getByRole('dialog', { name: 'Private follow-up' }).getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: 'Restore synthetic email run' }).click()
  await expect(target).toHaveCount(1)
  await expect(page.getByRole('article', { name: 'Retained email follow-up' })).toHaveCount(0)
  await expect(page.getByRole('article', { name: 'Private email conversation' })).toHaveCount(1)
  expect(await actions(page)).toEqual([])
})
