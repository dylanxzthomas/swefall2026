test('shares only edited calendar information after explicit review and leaves execution unapproved', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Review follow-up: Maya’s field trip' }).click()
  const sheet = page.getByRole('dialog', { name: 'Private follow-up' })
  await expect(sheet.getByLabel('End', { exact: true })).toHaveValue('')
  await expect(sheet.getByLabel('Still needed')).toHaveValue('What time does the trip finish?')
  await sheet.getByRole('button', { name: 'Prepare calendar review' }).click()
  await sheet.getByLabel('Text to share').fill('Maya’s trip October 12, 2026 at 9:30. End time is unknown.')
  await expect(sheet.getByRole('button', { name: 'Share & prepare calendar draft' })).toBeDisabled()
  await sheet.getByRole('checkbox', { name: /Share only this edited text/ }).check()
  await sheet.getByRole('button', { name: 'Share & prepare calendar draft' }).click()
  const recorded = await actions(page)
  expect(recorded).toHaveLength(1)
  expect(recorded[0].action).toBe('share-proposal-calendar')
  expect(recorded[0].data.text).not.toContain('Private tuition')
  expect(recorded[0].data.text).toBe('Maya’s trip October 12, 2026 at 9:30. End time is unknown.')
})
