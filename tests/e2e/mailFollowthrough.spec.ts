test('reviews, edits and keeps a private task, then completes it in Tasks', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: /Return Maya’s form/ }).click()
  const sheet = page.getByRole('dialog', { name: 'Private follow-up' })
  await sheet.getByLabel('Title', { exact: true }).fill('Return the signed form')
  await expect(sheet.getByRole('button', { name: 'Keep private task' })).toBeDisabled()
  await sheet.getByRole('button', { name: 'Save private edits' }).click()
  await expect(sheet.getByLabel('Title', { exact: true })).toHaveValue('Return the signed form')
  await expect(sheet.getByRole('status')).toHaveText('Private edits saved.')
  await expect(sheet.getByRole('button', { name: 'Keep private task' })).toBeEnabled()
  await sheet.getByRole('button', { name: 'Keep private task' }).click()
  await expect(page.getByRole('dialog', { name: 'Private follow-up' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Return the signed form/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Expire synthetic email source' }).click()
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  const tasks = page.getByRole('region', { name: 'Private tasks', exact: true })
  await expect(tasks.getByText('Return the signed form', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Return the signed form/ })).toHaveCount(0)
  await tasks.getByRole('button', { name: 'Open task', exact: true }).click()
  await expect(tasks.getByRole('textbox', { name: 'Details', exact: true })).toHaveValue('Bring a packed lunch.\nDue: 2026-10-10')
  await tasks.getByRole('button', { name: 'Mark done', exact: true }).click()
  await page.getByRole('button', { name: 'Finished', exact: true }).click()
  await expect(tasks.getByText('Return the signed form', { exact: true })).toBeVisible()
  await expect(tasks.getByText('Done by you', { exact: true })).toBeVisible()
  const recorded = await actions(page)
  expect(recorded.map(a => a.action)).toEqual(['edit-proposal', 'proposal-keep', 'private-task-done'])
  expect(recorded[0].data.input.routineRefs).toEqual([{ id: 'synthetic-mail-routine', version: 3 }])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
