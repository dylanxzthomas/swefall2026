import { test, expect } from '@playwright/test'

for (const colorScheme of ['light', 'dark'] as const) {
  test(`real device workspace appearance in ${colorScheme}`, async ({ page }) => {
    await page.clock.setFixedTime(new Date('2026-09-30T16:00:00Z'))
    await page.emulateMedia({ colorScheme, reducedMotion: 'reduce' })
    await page.goto('/')
    await expect(page.getByLabel('What can I handle?')).toBeEnabled()
    await expect(page).toHaveScreenshot(`home-${colorScheme}.png`)

    await page.getByRole('button', { name: 'Household settings' }).click()
    await page.getByText('Children and timezone', { exact: true }).click()
    await page.getByLabel('Household name', { exact: true }).fill('The Cedar Family')
    await page.getByLabel('Household timezone', { exact: true }).fill('America/Los_Angeles')
    await page.getByLabel('Add a child', { exact: true }).fill('Maya')
    await page.getByRole('button', { name: 'Save household', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button', { name: 'Household settings' }).click()
    await page.getByText('Children and timezone', { exact: true }).click()
    await page.getByText('Schools, contacts, and routines', { exact: true }).click()
    await expect(page.getByLabel('Child’s first name')).toHaveValue('Maya')
    await page.getByText('Children and timezone', { exact: true }).evaluate(summary => {
      const panel = summary.closest('details')!, sheet = summary.closest('dialog')!, header = sheet.querySelector(':scope > header')!
      sheet.scrollTop += panel.getBoundingClientRect().top - header.getBoundingClientRect().bottom
    })
    await expect(page).toHaveScreenshot(`household-${colorScheme}.png`)
    await page.getByText('Children and timezone', { exact: true }).click()
    await page.getByText('Schools, contacts, and routines', { exact: true }).click()
    await page.getByText('Your assistant', { exact: true }).click()
    await page.getByLabel('Assistant name', { exact: true }).scrollIntoViewIfNeeded()
    await expect(page.getByRole('button', { name: 'Close', exact: true })).toBeInViewport()
    // Reduced motion already disables app animation. Keep normal painting for
    // sticky dialog headers; capture-only style changes can omit visible text.
    await expect(page).toHaveScreenshot(`personalization-${colorScheme}.png`, { animations: 'allow', caret: 'initial' })
    await page.getByText('Expressions & motion', { exact: true }).click()
    const expressions = page.getByRole('region', { name: 'Character preview' })
    await expressions.getByRole('button', { name: 'Pleased', exact: true }).click()
    await page.locator('.dm-avatar-preview-details').evaluate(element => element.scrollIntoView({ block: 'start' }))
    await expect(expressions.locator('img')).toHaveCount(7)
    await expect.poll(() => expressions.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await expect(page).toHaveScreenshot(`expressions-${colorScheme}.png`)
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByLabel('What can I handle?').fill('Event: Maya’s museum trip\nDate: 2026-10-08\nTime: 8:30 AM to 2:30 PM\nLocation: North gate')
    await page.getByRole('button', { name: 'Send', exact: true }).click()

    const review = page.getByRole('dialog', { name: 'Review request' })
    await expect(review).toHaveCount(0)
    await page.getByRole('button', { name: /^Review request:/ }).click()
    const approve = review.getByRole('button', { name: 'Save to device plan', exact: true })
    await expect(approve).toBeEnabled()
    await expect(review.getByLabel('Shared notice')).toBeHidden()
    await expect(review.getByRole('button', { name: 'Save edits', exact: true })).toHaveCount(0)
    await expect(review.getByRole('heading', { name: 'Maya’s museum trip' })).toBeInViewport()
    await expect(approve).toBeInViewport()
    await expect(review.getByRole('button', { name: 'Close', exact: true })).toBeInViewport()
    await expect(page).toHaveScreenshot(`calendar-review-${colorScheme}.png`, { animations: 'allow', caret: 'initial' })
    await review.getByText('Keep in Library', { exact: true }).click()
    await review.getByRole('button', { name: 'Save Maya’s museum trip to Library', exact: true }).click()
    await expect(review.getByRole('status')).toContainText('Saved to Library')
    await review.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(page.locator('.dm-header .dm-avatar')).toHaveAttribute('data-mood', 'review')
    await expect(page).toHaveScreenshot(`conversation-${colorScheme}.png`)
    await page.getByRole('button', { name: 'Tasks', exact: true }).click()
    await page.getByRole('region', { name: 'Tasks', exact: true }).locator('.dm-task-new').click()
    const add = page.getByRole('dialog', { name: 'Add a task', exact: true })
    await add.getByLabel('Task', { exact: true }).fill('Pack Maya’s trip bag')
    await add.getByLabel(/Due date/).fill('2026-10-07')
    await add.getByRole('combobox', { name: 'Child', exact: true }).selectOption({ label: 'Maya' })
    await add.getByRole('button', { name: 'Add task', exact: true }).click()
    await expect(add).toHaveCount(0)
    await page.getByRole('region', { name: 'Tasks', exact: true }).locator('.dm-task-new').click()
    await add.getByRole('button', { name: 'Sola', exact: true }).click()
    await add.getByLabel('What should Sola prepare?', { exact: true }).fill('Draft a field-trip reply')
    await add.getByLabel('Prepare later', { exact: true }).check()
    await add.getByLabel('Preparation time', { exact: false }).fill('2026-10-07T16:00')
    await add.getByRole('button', { name: 'Schedule preparation', exact: true }).click()
    await expect(add).toHaveCount(0)
    await page.getByRole('button', { name: 'Library', exact: true }).click()
    await page.getByRole('button', { name: 'Tasks', exact: true }).click()
    await expect(page).toHaveScreenshot(`tasks-${colorScheme}.png`)
    await page.getByRole('button', { name: 'Library', exact: true }).click()
    await expect(page).toHaveScreenshot(`library-work-${colorScheme}.png`)
    await page.getByRole('button', { name: /Ready for review.*Maya’s museum trip/ }).click()
    await expect(review).toHaveCount(0)
    await expect(page.getByLabel('What can I handle?')).toBeVisible()
    await page.getByRole('button', { name: /^Review request:/ }).click()
    await review.getByText('Event notes', { exact: true }).click()
    await expect(review.locator('.dm-event-notes')).toContainText('Location: North gate')
    await review.getByText('Event notes', { exact: true }).click()
    await review.getByText('Edit details', { exact: true }).click()
    await review.getByLabel('Location', { exact: true }).fill('South gate')
    await expect(review.getByRole('button', { name: 'Save edits', exact: true })).toBeVisible()
    await review.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(review).toHaveCount(0)
    await page.getByRole('button', { name: 'Assistant', exact: true }).click()
    await page.getByRole('button', { name: 'Review request: Maya’s museum trip', exact: true }).click()
    await expect(review.getByRole('button', { name: 'Save edits', exact: true })).toHaveCount(0)
    await approve.click()
    await expect(review.getByText('Saved to your device plan')).toBeVisible()
    await review.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(page.locator('.dm-assistant-byline .dm-avatar').first()).toHaveAttribute('data-mood', 'done')
    await page.reload()
    await page.getByRole('button', { name: 'Plan', exact: true }).click()
    await expect(page.getByRole('button', { name: /Maya’s museum trip/ })).toContainText('South gate')
    await expect(page).toHaveScreenshot(`family-plan-${colorScheme}.png`)
    await page.getByRole('button', { name: 'Library', exact: true }).click()
    await page.getByRole('button', { name: 'Media', exact: true }).click()
    await expect(page).toHaveScreenshot(`library-media-${colorScheme}.png`)
  })
}
