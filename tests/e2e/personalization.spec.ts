import { test, expect } from '@playwright/test'

test('personal names and conversation persist without creating work or losing the composer between tabs', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Household settings' }).click()
  await page.getByText('Your assistant', { exact: true }).click()
  await page.getByLabel('Your name', { exact: true }).fill('Casey')
  await page.getByLabel('Assistant name', { exact: true }).fill('Jamie')
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved.')
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Jamie', exact: true })).toBeVisible()
  await expect(page.getByText('Hi, Casey.', { exact: true })).toBeVisible()
  await page.getByLabel('What can I handle?').fill('Hi Jamie')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByText(/Hi, Casey. What can I take off your list/)).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('Hi Jamie', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Jamie', exact: true })).toBeVisible()
  await page.getByLabel('What can I handle?').fill('An unsent school note')
  for (const name of ['Tasks', 'Library', 'Plan']) {
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click()
    if (name === 'Tasks') await expect(page.getByText('Your list has room to breathe.', { exact: true })).toBeVisible()
    await expect(page.getByLabel('What can I handle?')).toHaveCount(0)
  }
  await page.getByRole('button', { name: 'Assistant', exact: true }).click()
  await expect(page.getByLabel('What can I handle?')).toHaveValue('An unsent school note')
  await page.reload()
  await expect(page.getByLabel('What can I handle?')).toHaveValue('An unsent school note')
})

test('large text keeps navigation and settings reachable at phone width', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await page.addStyleTag({ content: 'html:root { font-size: 212.5%; }' })
  const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  for (const name of ['Tasks', 'Library', 'Plan', 'Assistant']) {
    const button = page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true })
    await expect(button).toBeInViewport()
    await button.click()
    await noOverflow()
  }
  await page.getByRole('button', { name: 'Household settings' }).click()
  const dialog = page.getByRole('dialog', { name: 'Household' })
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeInViewport()
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
})


test('household identity and avatar persist without replacing family details or custom assistant names', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Sola', exact: true })).toBeVisible()
  await expect(page.getByText('Your household', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Household settings' }).click()
  await page.getByText('Children and timezone', { exact: true }).click()
  await page.getByLabel('Household name', { exact: true }).fill('The Cedar Family')
  await page.getByLabel('Add a child', { exact: true }).fill('Maya')
  await page.getByRole('button', { name: 'Save household', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('The Cedar Family', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Household settings' }).click()
  await page.getByText('Your assistant', { exact: true }).click()
  await page.getByLabel('Assistant name', { exact: true }).fill('Jamie')
  await page.getByRole('button', { name: 'Initial', exact: true }).click()
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved.')
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Jamie', exact: true })).toBeVisible()
  await expect(page.locator('.dm-header .dm-avatar-initial')).toHaveText('J')
  await expect(page.getByText('The Cedar Family', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Household settings' }).click()
  await page.getByText('Children and timezone', { exact: true }).click()
  await expect(page.getByLabel('Child’s first name', { exact: true })).toHaveValue('Maya')
  await page.getByLabel('Household timezone', { exact: true }).fill('America/New_York')
  await page.getByRole('button', { name: 'Save household', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('The Cedar Family', { exact: true })).toBeVisible()
})
