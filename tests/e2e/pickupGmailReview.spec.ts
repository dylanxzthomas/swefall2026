import { expect, test, type Page } from '@playwright/test'
const start = async (page: Page, scenario = 'pickup-gmail') => {
  await page.goto(`/e2e.html?scenario=${scenario}`)
  await expect(page.getByText('Synthetic UI test · no sign-in or provider calls', { exact: true })).toBeVisible()
  await page.getByLabel('What can I handle?').fill('Ask Alex to collect Maya at the north gate.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Review request', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /^Review request:/ }).click()
  return page.getByRole('dialog', { name: 'Review request' })
}
const previews = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('synthetic-pickup-previews') ?? '[]'))
const approvals = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('synthetic-approvals') ?? '[]'))
for (const colorScheme of ['light', 'dark'] as const) test(`exact Gmail pickup review and edited approval fit a phone in ${colorScheme}`, async ({ page }) => {
  await page.emulateMedia({ colorScheme }); await page.setViewportSize({ width: 375, height: 667 })
  const review = await start(page), preview = review.getByRole('region', { name: 'Caregiver email to approve' })
  await expect(preview).toContainText('From: parent@google.example.test')
  await expect(preview).toContainText('To: alex@example.test')
  await expect(preview).toContainText('The caregiver must sign in with the email above before responding.')
  await expect(preview).toContainText('https://response.example.test/#pickup=[private link]')
  let recorded = await previews(page)
  await expect(preview.locator('p').nth(1)).toHaveText(recorded.at(-1).proof.body)
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeEnabled()
  expect(await review.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await review.getByText('Edit details', { exact: true }).click()
  const edited = 'Can you collect Maya? Please meet at the south gate. 🌞'
  await review.getByRole('textbox', { name: 'Request message', exact: true }).fill(edited)
  await expect(preview).toContainText(edited)
  recorded = await previews(page)
  expect(recorded.at(-1).payload.message).toBe(edited)
  await expect(preview.locator('p').nth(1)).toHaveText(recorded.at(-1).proof.body)
  await review.getByText('Edit details', { exact: true }).click()
  expect(await review.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: `test-results/pickup-gmail-review-${colorScheme}.png`, animations: 'disabled' })
  await review.getByRole('button', { name: 'Send pickup request', exact: true }).click()
  await expect(review.getByText('Request email accepted · awaiting response', { exact: true })).toBeVisible()
  const approved = await approvals(page)
  expect(approved).toHaveLength(1)
  expect(approved[0]).toMatchObject({ id: 'action', revision: 2, selectionVersion: 3, deliveryChannel: 'email', pickupEmailHash: recorded.at(-1).proof.hash })
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('synthetic-state')!).jobs[0].actions[0].payload.message)).toBe(edited)
  await expect(review.getByText('Caregiver acceptance recorded', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
test('approval stays disabled while the exact caregiver email is loading', async ({ page }) => {
  const review = await start(page, 'pickup-gmail-loading')
  await expect(review.getByRole('status')).toContainText('Checking how this request will reach the caregiver')
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeDisabled()
  expect(await approvals(page)).toEqual([])
  await page.getByRole('button', { name: 'Finish synthetic email preview' }).evaluate((button: HTMLButtonElement) => button.click())
  await expect(review.getByRole('region', { name: 'Caregiver email to approve' })).toBeVisible()
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeEnabled()
})
test('a failed caregiver email preview blocks approval without a provider receipt', async ({ page }) => {
  const review = await start(page, 'pickup-gmail-error')
  await expect(review.getByRole('alert')).toContainText('Caregiver sending account is unavailable')
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeDisabled()
  expect(await approvals(page)).toEqual([])
  await expect(review.getByText('Request email accepted · awaiting response', { exact: true })).toHaveCount(0)
})
test('a changed sending account invalidates the old review until the parent loads the current one', async ({ page }) => {
  const review = await start(page, 'pickup-gmail-race'), preview = review.getByRole('region', { name: 'Caregiver email to approve' })
  await expect(preview).toContainText('From: parent@google.example.test')
  const oldHash = (await previews(page)).at(-1).proof.hash
  await page.getByRole('button', { name: 'Simulate changed pickup sender' }).evaluate((button: HTMLButtonElement) => button.click())
  await expect(review.getByText('This review changed.', { exact: false })).toBeVisible()
  await expect(preview).toContainText('From: changed-parent@google.example.test')
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeDisabled()
  expect(await approvals(page)).toEqual([])
  await review.getByRole('button', { name: 'Load latest review', exact: true }).click()
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeEnabled()
  const latest = (await previews(page)).at(-1)
  expect(latest.proof.hash).not.toBe(oldHash)
  await review.getByRole('button', { name: 'Send pickup request', exact: true }).click()
  expect((await approvals(page))[0]).toMatchObject({ selectionVersion: 4, pickupEmailHash: latest.proof.hash })
})
test('an optional single reminder is previewed and included in the exact approval hash', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const review = await start(page), preview = review.getByRole('region', { name: 'Caregiver email to approve' })
  await expect(preview).toBeVisible()
  await review.getByText('Edit details', { exact: true }).click()
  await review.getByRole('checkbox', { name: 'Allow one reminder with the same message' }).check()
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeDisabled()
  await review.getByLabel('Send one reminder at', { exact: true }).fill('2027-05-05T09:30')
  await expect(preview.getByText('One reminder · 2027-05-05T09:30:00Z', { exact: true })).toBeVisible()
  await preview.getByText('One reminder · 2027-05-05T09:30:00Z', { exact: true }).click()
  const latest = (await previews(page)).at(-1)
  await expect(preview).toContainText(latest.proof.reminder.body)
  expect(latest.proof.reminder.at).toBe('2027-05-05T09:30:00Z')
  await expect(review.getByRole('button', { name: 'Send pickup request', exact: true })).toBeEnabled()
  expect(await review.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await review.getByRole('button', { name: 'Send pickup request', exact: true }).click()
  expect((await approvals(page))[0].pickupEmailHash).toBe(latest.proof.hash)
})
