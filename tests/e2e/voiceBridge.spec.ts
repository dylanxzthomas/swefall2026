test('remembered voice starts only after a fresh microphone tap after reload',async({page})=>{
  await open(page);await page.getByRole('button',{name:'Start voice',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Microphone is on')
  await page.getByRole('button',{name:'Close voice',exact:true}).click()
  await page.reload()
  const observations=page.getByRole('list',{name:'Synthetic voice observations'})
  await expect(observations.getByText('microphone requested',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Voice',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Microphone is on')
  await expect(page.getByRole('button',{name:'Start voice',exact:true})).toHaveCount(0)
  await expect(observations.getByText('microphone requested',{exact:true})).toHaveCount(1)
})

