test('discloses private saved requests, waits for actual preparation, and ignores duplicate provider events',async({page})=>{
  await open(page)
  const talk=page.getByRole('button',{name:'Start voice',exact:true})
  await expect(talk).toBeEnabled()
  const disclosure=page.locator('.dm-voice-disclosure')
  await expect(disclosure).toBeVisible();await expect(disclosure).toContainText('use Anthropic and stay private for up to 30 days')
  await expect(disclosure).toContainText('results go to OpenAI');await expect(disclosure).toContainText('Your choice is remembered on this device; actions still need review')
  await talk.click();await expect(page.getByRole('status')).toContainText('Microphone is on')
  await page.getByRole('button',{name:'Mute microphone',exact:true}).click();await expect(page.getByRole('status')).toContainText('Microphone is muted')
  await page.getByRole('button',{name:'Unmute microphone',exact:true}).click();await expect(page.getByRole('status')).toContainText('Microphone is on')
  await page.getByRole('button',{name:'Simulate spoken household request'}).click()
  await page.getByRole('button',{name:'Repeat provider event fifty times'}).click()
  const observations=page.getByRole('list',{name:'Synthetic voice observations'})
  await expect(observations.getByText('private request What needs my attention?',{exact:true})).toHaveCount(1)
  await expect(observations.getByText('provider output',{exact:false})).toHaveCount(0)
  await page.getByRole('button',{name:'Finish synthetic preparation'}).click()
  await expect(observations.getByText('provider output',{exact:false})).toHaveCount(2)
  const outputs=await observations.getByText('provider output',{exact:false}).allTextContents()
  expect(JSON.parse(JSON.parse(outputs[0].replace('provider output ', '')).item.output)).toMatchObject({status:'complete',reviewRequired:true})
  await expect(observations).toContainText('Nothing was sent.')
  await page.getByRole('button',{name:'Stop voice',exact:true}).click()
  await expect(observations).toContainText('microphone stopped')
  await expect(observations).toContainText('provider stopped')
})
