test('main chat joins partial captions, replaces with one final, and switches view without restarting',async({page})=>{
  await open(page)
  const observations=page.getByRole('list',{name:'Synthetic voice observations'}), chat=page.getByRole('region',{name:'Main conversation'})
  await expect(observations.getByText('microphone requested',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Start voice',exact:true}).click()
  await expect(chat.getByRole('status')).toContainText('Microphone is on')
  await page.getByRole('button',{name:'Simulate partial speech',exact:true}).click()
  await expect(chat.locator('.dm-voice-caption')).toHaveCount(1)
  await expect(chat.getByRole('log')).toContainText('What is next?')
  await expect(chat.getByRole('status')).toHaveText('Listening to you…')
  await page.getByRole('button',{name:'Finalize speech twice',exact:true}).click()
  await expect(chat.locator('.dm-voice-caption')).toHaveCount(1)
  await expect(chat.locator('.dm-voice-caption')).toHaveAttribute('data-final','true')
  await expect(chat.getByRole('log')).toContainText('What is next for tomorrow?')
  await page.getByRole('button',{name:'Show character',exact:true}).click()
  await expect(chat.getByLabel('Sola voice character')).toBeVisible()
  await expect(chat.getByRole('log')).toHaveCount(0)
  await page.getByRole('button',{name:'Simulate speaking',exact:true}).click()
  await expect(chat.getByRole('status')).toHaveText('Sola is speaking…')
  await expect(chat.locator('.dm-voice-call')).toHaveAttribute('data-activity','speaking')
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(chat.locator('.dm-voice-character-ring')).toHaveCSS('animation-name','none')
  await page.getByRole('button',{name:'Finish speaking',exact:true}).click()
  await expect(chat.getByRole('status')).toContainText('Microphone is on')
  await page.getByRole('button',{name:'Show transcript',exact:true}).click()
  await expect(chat.locator('.dm-voice-caption')).toHaveCount(2)
  await expect(chat.getByRole('log')).toContainText('Let me check the family plan.')
  await expect(observations.getByText('voice started',{exact:true})).toHaveCount(1)
  await expect(observations.getByText('microphone requested',{exact:true})).toHaveCount(1)
  await expect(observations.getByText('copied to composer',{exact:true})).toHaveCount(0)
  await expect(observations.getByText('private request',{exact:false})).toHaveCount(0)
  await page.getByRole('button',{name:'Show character',exact:true}).click()
  await page.getByRole('button',{name:'Stop voice',exact:true}).click()
  await expect(chat.getByRole('status')).toContainText('Voice ended')
  await page.getByRole('button',{name:'Show transcript',exact:true}).click()
  await page.getByRole('button',{name:'Send late caption',exact:true}).click()
  await expect(chat.locator('.dm-voice-caption')).toHaveCount(2)
  await expect(chat).not.toContainText('This late text must never appear.')
  await page.getByRole('button',{name:'Close voice',exact:true}).click()
  await expect(chat.getByRole('log')).toHaveCount(0)
  await page.getByRole('button',{name:'Voice',exact:true}).click()
  await expect(chat.getByRole('status')).toContainText('Microphone is on')
  await expect(page.getByRole('button',{name:'Start voice',exact:true})).toHaveCount(0)
  await expect(observations.getByText('voice started',{exact:true})).toHaveCount(2)
})

