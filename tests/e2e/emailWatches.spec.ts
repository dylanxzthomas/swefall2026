import { expect, test, type Page } from '@playwright/test'
async function open(page: Page, scenario = 'email-watch') {
  await page.goto(`/e2e.html?scenario=${scenario}`)
  await page.getByText('Email watch', { exact: true }).click()
}
async function configure(page: Page) {
  await page.getByRole('button', { name: 'Set up email watch', exact: true }).click()
  await page.getByLabel('Sender email addresses').fill('school@example.test')
  await page.getByRole('checkbox').check()
}
const actions = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('watch-actions') ?? '[]'))
test('watch requires explicit filter and consent; enabled and requested never imply a completed check', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: 'dark' })
  await open(page)
  expect(await actions(page)).toEqual([])
  await page.getByRole('button', { name: 'Set up email watch', exact: true }).click()
  await page.getByLabel('Sender email addresses').fill('school@example.test')
  await expect(page.getByRole('button', { name: 'Enable this watch', exact: true })).toBeDisabled()
  await page.getByRole('checkbox').check()
  expect(await actions(page)).toEqual([])
  await expect(page.getByText(/Nothing is sent or added to a calendar without approval/)).toBeVisible()
  const sheet = page.getByRole('dialog', { name: 'Household' })
  expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('email-watch-consent-dark.png') })
  await page.getByRole('button', { name: 'Enable this watch', exact: true }).click()
  await expect(page.getByText('Last completed check: Not checked yet', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Check now', exact: true }).click()
  await expect(page.getByText('Checking selected senders…', { exact: true })).toBeVisible()
  await expect(page.getByText('Last completed check: Not checked yet', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause watch', exact: true }).click()
  await expect(page.getByText('Paused', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Resume watch', exact: true }).click()
  await page.getByRole('button', { name: 'Edit watch', exact: true }).click()
  await page.getByLabel('Watch name').fill('School letters')
  await expect(page.getByRole('button', { name: 'Save changes & pause', exact: true })).toBeDisabled()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Save changes & pause', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'School letters', exact: true })).toBeVisible()
  await expect(page.getByText('Paused', { exact: true })).toBeVisible()
  expect(await actions(page)).toHaveLength(5)
})
test('missing setup explains the limit and does not offer a working-looking connection', async ({ page }) => {
  await open(page, 'email-watch-unconfigured')
  await expect(page.getByText('Gmail connection setup is still needed. No inbox is being checked.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Connect Gmail reading', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Set up email watch', exact: true })).toBeDisabled()
  expect(await actions(page)).toEqual([])
})
test('stale edits preserve the parent draft and never announce a successful save', async ({ page }) => {
  await open(page, 'email-watch-stale'); await configure(page)
  await page.getByRole('button', { name: 'Enable this watch', exact: true }).click()
  await page.getByRole('button', { name: 'Edit watch', exact: true }).click()
  await page.getByLabel('Watch name').fill('Changed title'); await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Save changes & pause', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('watch changed')
  await expect(page.getByLabel('Watch name')).toHaveValue('Changed title')
  await expect(page.getByText('Changes saved. Resume when you are ready to use this watch.', { exact: true })).toHaveCount(0)
  expect(await actions(page)).toHaveLength(1)
})
test('pending confirmation locks the editor and prevents duplicate submissions', async ({ page }) => {
  await open(page, 'email-watch-slow'); await configure(page)
  await page.getByRole('button', { name: 'Enable this watch', exact: true }).click()
  await expect(page.getByLabel('Watch name')).toBeDisabled(); await expect(page.getByLabel('Sender email addresses')).toBeDisabled()
  await expect(page.getByRole('checkbox')).toBeDisabled(); await expect(page.getByRole('button', { name: 'Enable this watch', exact: true })).toBeDisabled()
  await expect(page.getByRole('heading', { name: 'School & activity updates', exact: true })).toBeVisible()
  expect(await actions(page)).toHaveLength(1)
})
