import { expect, test, type Page } from '@playwright/test'

async function workspace(page: Page) {
  return page.evaluate(() => new Promise<any>((resolve,reject) => {
    const request = indexedDB.open('daymark-device-v1')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => { const db = request.result, tx = db.transaction('workspace'), value = tx.objectStore('workspace').get('current'); value.onsuccess = () => resolve(value.result); tx.oncomplete = () => db.close() }
  }))
}
async function ask(page: Page, text: string) { await page.getByLabel('What can I handle?').fill(text); await page.getByRole('button', { name: 'Send', exact: true }).click() }
const review = (page: Page) => page.getByRole('dialog', { name: 'Review routine', exact: true })
const details = (page: Page) => page.getByRole('dialog', { name: 'Routine details', exact: true })
async function tasks(page: Page) { await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Tasks', exact: true }).click() }

test('chat previews a routine, cancellation preserves the request, and confirmation persists an editable schedule', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  const text = 'Every Sunday at 7pm, add packing school bags to my tasks'
  await ask(page, text)
  await expect(review(page)).toBeVisible()
  await expect(review(page).getByLabel('Time', { exact: true })).toHaveValue('19:00')
  expect((await workspace(page)).state.routines ?? []).toHaveLength(0)
  await review(page).getByRole('button', { name: 'Close routine details' }).click()
  await expect(page.getByLabel('What can I handle?')).toHaveValue(text)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await review(page).getByLabel('Routine name').fill('Sunday school bags')
  await review(page).getByLabel('Task to add').fill('Pack school bags')
  await expect(review(page)).toContainText('only the latest missed occurrence')
  expect(await review(page).evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('routine-review-dark.png'), animations: 'disabled' })
  await review(page).getByRole('button', { name: 'Save routine', exact: true }).click()
  await expect(review(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open routine Sunday school bags', exact: true })).toBeVisible()
  const saved = (await workspace(page)).state
  expect(saved.routines).toHaveLength(1); expect(saved.personalTasks).toEqual([]); expect(saved.jobs).toEqual([])
  expect(saved.routines[0].definition.schedule).toMatchObject({ weekdays: [7], time: '19:00' })
  await page.reload(); await tasks(page)
  await page.getByRole('button', { name: 'Open routine Sunday school bags' }).click()
  await details(page).getByRole('button', { name: 'Pause routine', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Routines', exact: true })).toContainText('Paused')
  await page.getByRole('button', { name: 'Open routine Sunday school bags' }).click()
  await details(page).getByRole('button', { name: 'Resume routine', exact: true }).click()
  await page.getByRole('button', { name: 'Open routine Sunday school bags' }).click()
  await details(page).getByRole('button', { name: 'Remove routine', exact: true }).click()
  expect((await workspace(page)).state.routines).toHaveLength(1)
  await details(page).getByRole('button', { name: 'Remove routine', exact: true }).click()
  await expect(details(page)).toHaveCount(0)
  expect((await workspace(page)).state.routines).toEqual([])
})

test('vague time stays blank and invalid repeat patterns cannot silently become a daily task', async ({ page }) => {
  await page.goto('/')
  await ask(page, 'Every Sunday evening, add laundry to my tasks')
  await expect(review(page).getByLabel('Time', { exact: true })).toHaveValue('')
  await review(page).getByRole('button', { name: 'Save routine', exact: true }).click()
  expect((await workspace(page)).state.routines ?? []).toHaveLength(0)
  await review(page).getByRole('button', { name: 'Close routine details' }).click()
  await ask(page, 'Every other Sunday at 7pm add laundry to my tasks')
  await expect(review(page)).toContainText('other repeat patterns are not supported')
  await review(page).getByLabel('Time', { exact: true }).fill('19:00')
  await review(page).getByRole('button', { name: 'Save routine', exact: true }).click()
  await expect(review(page).getByRole('alert')).toBeVisible()
  expect((await workspace(page)).state.routines ?? []).toHaveLength(0)
})

test('a missed local routine creates one unfinished task and shows its real completion in history', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-05T08:59:00Z')); await page.goto('/')
  await tasks(page); await page.getByRole('button', { name: 'Add routine', exact: true }).click()
  await review(page).getByLabel('Routine name').fill('Library bag')
  await review(page).getByLabel('Task to add').fill('Pack library books')
  await review(page).getByRole('combobox', { name: 'Repeat', exact: true }).selectOption('daily')
  await review(page).getByLabel('Time', { exact: true }).fill('09:00')
  await review(page).getByLabel('Routine timezone').fill('UTC')
  await review(page).getByRole('button', { name: 'Save routine', exact: true }).click()
  await expect(review(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open routine Library bag', exact: true })).toBeVisible()
  await page.goto('about:blank'); await page.clock.setFixedTime(new Date('2026-10-09T10:00:00Z')); await page.goto('/'); await tasks(page)
  await expect(page.getByRole('checkbox', { name: 'Mark Pack library books complete', exact: true })).toBeVisible()
  expect((await workspace(page)).state.personalTasks).toHaveLength(1)
  await page.getByRole('checkbox', { name: 'Mark Pack library books complete', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Mark Pack library books not done', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Open routine Library bag', exact: true }).click()
  await details(page).getByText('Recent occurrences', { exact: true }).click()
  await expect(details(page)).toContainText('Marked done by the parent.')
  await expect(details(page)).toContainText('2026-10-09')
  await expect(details(page)).toContainText('Latest missed occurrence')
})

test('routine edits stay visible while another tab pauses it and stale saving is blocked', async ({ page, context }) => {
  await page.goto('/'); await ask(page, 'Every day at 8am add pack lunch')
  await review(page).getByRole('button', { name: 'Save routine', exact: true }).click()
  await page.getByRole('button', { name: 'Open routine pack lunch', exact: true }).click()
  await details(page).getByLabel('Task to add').fill('Pack lunch and water')
  const other = await context.newPage(); await other.goto('/'); await tasks(other)
  await other.getByRole('button', { name: 'Open routine pack lunch', exact: true }).click()
  await details(other).getByRole('button', { name: 'Pause routine', exact: true }).click()
  await expect(details(page).getByRole('alert')).toContainText('changed elsewhere')
  await expect(details(page).getByLabel('Task to add')).toHaveValue('Pack lunch and water')
  await expect(details(page).getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  expect((await workspace(page)).state.routines[0].definition.outcome.task.title).toBe('pack lunch')
  await other.getByRole('button', { name: 'Open routine pack lunch', exact: true }).click()
  await details(other).getByRole('button', { name: 'Remove routine', exact: true }).click()
  await details(other).getByRole('button', { name: 'Remove routine', exact: true }).click()
  await expect(details(other)).toHaveCount(0)
  await expect(details(page).getByLabel('Task to add')).toHaveValue('Pack lunch and water')
  await expect(details(page).getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
})
