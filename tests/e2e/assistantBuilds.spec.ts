test('keeps a private task after its source expires and supports retained edits, completion, reopening and removal', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: /Return the permission form.*For you/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Sola’s preparation' })
  await dialog.getByLabel('Prepared text').fill('Return only the signed form on Friday.')
  await dialog.getByRole('button', { name: 'Keep private task' }).click()
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  const tasks=page.getByRole('region',{name:'Private tasks'})
  await expect(tasks.getByText('Return the permission form',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:/Return the permission form.*Kept privately/})).toHaveCount(0)
  await page.getByRole('button',{name:'Simulate expired assistant source'}).click()
  await page.reload();await page.getByRole('button',{name:'Tasks',exact:true}).click()
  await tasks.getByRole('button',{name:'Open task'}).click()
  const review=page.getByRole('region',{name:'Edit private task'})
  await expect(review.getByRole('textbox',{name:'Details',exact:true})).toHaveValue('Return only the signed form on Friday.')
  await review.getByRole('textbox',{name:'Task',exact:true}).fill('Return the signed permission form')
  await review.getByRole('textbox',{name:'Details',exact:true}).fill('Only these reviewed details stay saved.')
  await review.getByRole('button',{name:'Save edits'}).click()
  await expect(review.getByRole('status')).toContainText('saved privately')
  await tasks.screenshot({path:'/private/tmp/sola-retained-private-task-oct14.png',animations:'disabled'})
  await review.getByRole('button',{name:'Mark done',exact:true}).click()
  await expect(tasks.getByText('Done by you')).toBeVisible()
  await tasks.getByRole('button',{name:'Review completed task'}).click()
  await review.getByRole('button',{name:'Reopen task'}).click()
  await tasks.getByRole('button',{name:'Open task'}).click()
  await review.getByRole('button',{name:'Remove task',exact:true}).click()
  await review.getByRole('button',{name:'Remove task',exact:true}).click()
  await expect(tasks).toHaveCount(0)
  await page.getByRole('button',{name:'Replay original private task keep'}).click()
  await expect(tasks).toHaveCount(0)
  const recorded=await actions(page)
  expect(recorded.map(a=>a.action)).toEqual(['assistant-keep','private-task-edit','private-task-done','private-task-done','private-task-remove'])
  expect(JSON.stringify(recorded)).not.toContain('tuition')
  expect(recorded.every(a=>!a.action.includes('provider'))).toBe(true)
})
