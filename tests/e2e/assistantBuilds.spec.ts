test('reviews coordinator email privately in chat, preserves edited reply and reopens it from Tasks without Gmail approval', async ({ page }) => {
  await start(page, 'assistant-builds-private-reply')
  await page.getByRole('button', { name: /Reply about the museum trip.*Private review/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Sola’s preparation' })
  await expect(dialog.getByText(/Private reply from parent@example.test to school@example.test/)).toBeVisible()
  await expect(dialog.getByRole('checkbox')).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Share & prepare for approval' })).toHaveCount(0)
  await dialog.getByLabel('Prepared text').fill('Thank you. Maya will bring the signed form Friday.')
  await dialog.getByRole('button', { name: 'Review private reply', exact: true }).click()
  const reply = dialog.getByRole('region', { name: 'Private Gmail draft' })
  await expect(reply.getByLabel('To', { exact: true })).toHaveValue('school@example.test')
  await expect(reply.getByLabel('Subject', { exact: true })).toHaveValue('Re: Synthetic museum attachment')
  await expect(reply.getByLabel('Reply', { exact: true })).toHaveValue('Thank you. Maya will bring the signed form Friday.')
  await expect(reply.getByRole('button', { name: 'Approve & save Gmail draft' })).toBeDisabled()
  await expect(reply.getByRole('button', { name: 'Approve & send email' })).toHaveCount(0)
  await reply.getByLabel('Reply', { exact: true }).fill('My final private correction.')
  await reply.getByRole('button', { name: 'Save private edits' }).click()
  await expect(reply.getByRole('status')).toContainText('Private edits saved.')
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await page.getByRole('button', { name: /Reply about the museum trip.*Review draft/ }).click()
  await expect(page.getByRole('region', { name: 'Conversation', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Reply about the museum trip.*Review draft/ }).click()
  await expect(dialog.getByLabel('Reply', { exact: true })).toHaveValue('My final private correction.')
  await expect(dialog.getByRole('button', { name: 'Approve & save Gmail draft' })).toBeDisabled()
  expect((await actions(page)).map(a => a.action)).toEqual(['assistant-reply', 'private-reply-edit'])
  const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('assistant-builds-state:assistant-builds-private-reply')!))
  expect(saved.jobs).toHaveLength(1)
  expect(saved.mailDrafts).toHaveLength(1)
  expect(saved.mailDrafts[0].status).toBe('review')
})
