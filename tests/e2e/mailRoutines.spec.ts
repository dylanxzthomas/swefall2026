test('reviews learned email routines privately without a household-sharing checkbox or automatic activation', async ({ page }) => {
  await start(page)
  await page.getByRole('region', { name: 'Learning suggestions' }).getByRole('button', { name: 'Review suggestion' }).click()
  const review = page.getByRole('region', { name: 'Review learning suggestion' })
  await expect(review.getByRole('checkbox')).toHaveCount(0)
  await expect(review).toContainText('Saved privately and paused')
  await review.getByLabel('When a new email…').fill('asks for an updated permission form')
  await review.getByLabel('What should Sola prepare?').fill('Prepare only the current form deadline and a short reply.')
  await review.getByRole('button', { name: 'Save edits', exact: true }).click()
  await expect(review.getByRole('status')).toContainText('Edits saved privately')
  await review.getByRole('button', { name: 'Save private routine', exact: true }).click()
  const records = await actions(page)
  expect(records.map(item => item.action)).toEqual(['learning-edit', 'learning-approve'])
  expect(records[1].data).toMatchObject({ shareConfirmed: false, savedState: 'paused', version: 2, value: { condition: 'asks for an updated permission form', instruction: 'Prepare only the current form deadline and a short reply.' } })
  expect((await savedState(page)).mailRoutines[0].state).toBe('paused')
  expect((await savedState(page)).jobs).toEqual([])
  await expect(page.getByRole('button', { name: 'Open email routine School forms' })).toBeVisible()
})

